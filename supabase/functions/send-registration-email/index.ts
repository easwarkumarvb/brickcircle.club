import {readBoundedJSON,RequestBodyError} from '../_shared/bounded-json.mjs';
import {createClient} from 'npm:@supabase/supabase-js@2.57.4';
import nodemailer from 'npm:nodemailer@^9';

const OWNER_EMAIL='hello@brickcircle.club';
const SENDER={name:'BrickCircle',address:OWNER_EMAIL};
const SMTP_HOST='smtpout.secureserver.net';
const SMTP_PORT=465;
const json=(body:unknown,status=200)=>new Response(JSON.stringify(body),{status,headers:{'content-type':'application/json'}});
const uuid=/^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
const escapeHtml=(value:string)=>value.replace(/[&<>"']/g,(character)=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[character] as string));

async function equalSecret(left:string,right:string){
  const encoder=new TextEncoder();
  const [a,b]=await Promise.all([crypto.subtle.digest('SHA-256',encoder.encode(left)),crypto.subtle.digest('SHA-256',encoder.encode(right))]);
  const av=new Uint8Array(a),bv=new Uint8Array(b);let result=av.length^bv.length;
  for(let index=0;index<Math.min(av.length,bv.length);index++)result|=av[index]^bv[index];
  return result===0;
}

Deno.serve(async(req:Request)=>{
  if(req.method!=='POST')return json({error:'Method not allowed'},405);
  const expected=Deno.env.get('EMAIL_DELIVERY_WEBHOOK_SECRET')||'';
  const supplied=req.headers.get('x-brickcircle-email-secret')||'';
  if(!expected||!supplied||!await equalSecret(expected,supplied))return json({error:'Unauthorized'},401);

  const supabaseUrl=Deno.env.get('SUPABASE_URL');
  const serviceRoleKey=Deno.env.get('SUPABASE_SERVICE_ROLE_KEY');
  const smtpUsername=Deno.env.get('GODADDY_SMTP_USERNAME');
  const smtpPassword=Deno.env.get('GODADDY_SMTP_PASSWORD');
  if(!supabaseUrl||!serviceRoleKey||!smtpUsername||!smtpPassword)return json({error:'Registration email worker is not configured'},503);

  let input;
  try { input=await readBoundedJSON(req); } catch(error) { return json({error:error instanceof RequestBodyError?error.message:'Invalid JSON.'},error instanceof RequestBodyError?error.status:400); }
  const requestedId=String(input?.record?.id||input?.delivery_id||'');
  if(requestedId&&!uuid.test(requestedId))return json({error:'Invalid delivery id'},400);

  const db=createClient(supabaseUrl,serviceRoleKey,{auth:{persistSession:false,autoRefreshToken:false}});
  const smtp=nodemailer.createTransport({
    host:SMTP_HOST,
    port:SMTP_PORT,
    secure:true,
    auth:{user:smtpUsername,pass:smtpPassword},
    connectionTimeout:10000,
    greetingTimeout:10000,
    socketTimeout:15000
  });
  const {data:deliveries,error:claimError}=await db.rpc('claim_registration_email_deliveries',{p_limit:requestedId?1:20,p_delivery_id:requestedId||null});
  if(claimError)return json({error:'Could not claim registration email deliveries'},500);

  let sent=0,retrying=0,permanentFailures=0;
  for(const delivery of deliveries||[]){
    let registrantEmail:string|null=null;
    try{
      const {data,error}=await db.auth.admin.getUserById(delivery.registered_user_id);
      if(error)throw error;
      const user=data.user;
      if(!user?.email)throw new Error('New account has no Auth email');
      registrantEmail=user.email;
      const metadata=user.user_metadata||{};
      const displayName=String(metadata.full_name||metadata.display_name||metadata.name||'').trim().slice(0,120);
      const registeredAt=String(user.created_at||delivery.created_at||new Date().toISOString());
      const subject='New BrickCircle member registered';
      const lines=[
        'A new member account was created on BrickCircle.club.',
        '',
        `Name: ${displayName||'Not provided'}`,
        `Email: ${registrantEmail}`,
        `Registered: ${registeredAt}`,
        '',
        'This notification was generated by the BrickCircle Auth registration event.'
      ];
      const html=`<!doctype html><html><body style="margin:0;background:#f6f3ed;font-family:Arial,sans-serif;color:#172033"><div style="max-width:600px;margin:auto;padding:32px 20px"><div style="background:#fff;border:1px solid #e8e1d6;border-radius:16px;padding:28px"><p style="margin:0 0 12px;color:#b45309;font-weight:700">BrickCircle</p><h1 style="font-size:24px;margin:0 0 16px">New member registered</h1><p style="line-height:1.6">A new account was created on BrickCircle.club.</p><p><strong>Name:</strong> ${escapeHtml(displayName||'Not provided')}<br><strong>Email:</strong> ${escapeHtml(registrantEmail)}<br><strong>Registered:</strong> ${escapeHtml(registeredAt)}</p></div></div></body></html>`;
      const sentMessage=await smtp.sendMail({
        from:SENDER,
        replyTo:OWNER_EMAIL,
        to:OWNER_EMAIL,
        subject,
        text:lines.join('\n'),
        html,
        messageId:`<registration-${delivery.id}@brickcircle.club>`,
        headers:{'X-BrickCircle-Delivery-ID':String(delivery.id)}
      });
      const {error:updateError}=await db.from('registration_email_deliveries').update({status:'sent',provider_message_id:String(sentMessage.messageId||'')||null,last_error:null,sent_at:new Date().toISOString(),updated_at:new Date().toISOString()}).eq('id',delivery.id);
      if(updateError)throw updateError;
      sent++;
    }catch(error){
      const message=String(error instanceof Error?error.message:error).slice(0,1000);
      const attempts=Number(delivery.attempt_count||0);
      if(attempts<3){
        const delaySeconds=attempts<=1?60:300;
        await db.from('registration_email_deliveries').update({status:'retry',last_error:message,next_attempt_at:new Date(Date.now()+delaySeconds*1000).toISOString(),updated_at:new Date().toISOString()}).eq('id',delivery.id);
        retrying++;
      }else{
        await db.from('registration_email_deliveries').update({status:'permanent_failure',last_error:message,updated_at:new Date().toISOString()}).eq('id',delivery.id);
        permanentFailures++;
      }
    }
  }
  smtp.close();
  return json({ok:true,claimed:(deliveries||[]).length,sent,retrying,permanent_failures:permanentFailures});
});
